"""Complete symbolic verifier for tag-automaton magma models.

Carrier: the inductive type generated by constructors (tags). 'G' is the generator
constructor (arity 1, its argument is an opaque Nat atom of sort 'N').  Every other
tag has arity = number of arguments.  The operation is an ordered rule list; each
rule is (pat_u, pat_v, rhs) with pattern variables '$a' (non-linear = equality
check) and constructor patterns (tag, *args).  The default rule is J(u,v) (fresh
product).  verify(law) returns the list of failing branches, each with its
constraint state, or [] if the law holds for every element of the carrier.
"""
import itertools
_ctr = itertools.count()


class Var:
    __slots__ = ('id', 'sort', 'name')

    def __init__(self, sort='M', name=None):
        self.id = next(_ctr)
        self.sort = sort
        self.name = name

    def __repr__(self):
        return (self.name or ('n' if self.sort == 'N' else 'v')) + str(self.id)

    def __hash__(self):
        return self.id

    def __eq__(self, o):
        return self is o


class State:
    __slots__ = ('sub', 'excl', 'diseq', 'subs')

    def __init__(self, sub=None, excl=None, diseq=None, subs=None):
        self.sub = sub if sub is not None else {}
        self.excl = excl if excl is not None else {}
        self.diseq = diseq if diseq is not None else []
        self.subs = subs if subs is not None else {}   # Var -> [terms it is a PROPER subterm of]

    def copy(self):
        return State(dict(self.sub), {k: set(v) for k, v in self.excl.items()}, list(self.diseq),
                     {k: list(v) for k, v in self.subs.items()})

    def contains(self, t, s):
        """is s a (non-strict) subterm of t (both resolved)?"""
        if t == s:
            return True
        if isinstance(t, Var):
            return False
        return any(self.contains(a, s) for a in t[1:])

    def subs_ok(self):
        for v, terms in self.subs.items():
            vt = self.resolve(v)
            for s in terms:
                st_ = self.resolve(s)
                if self.contains(vt, st_):      # v == s or v contains s: impossible for v ⊂ s
                    return False
        return True

    def resolve(self, t):
        while isinstance(t, Var) and t in self.sub:
            t = self.sub[t]
        if isinstance(t, Var):
            return t
        return (t[0],) + tuple(self.resolve(a) for a in t[1:])

    def consistent(self):
        for (a, b) in self.diseq:
            if self.resolve(a) == self.resolve(b):
                return False
        return self.subs_ok()

    def occurs(self, v, t):
        t = self.resolve(t)
        if isinstance(t, Var):
            return t is v
        return any(self.occurs(v, a) for a in t[1:])

    def unify(self, s, t):
        """Try to unify; returns new State or None.  Occurs check = level argument."""
        st = self.copy()
        stack = [(s, t)]
        while stack:
            a, b = stack.pop()
            a = st.resolve(a)
            b = st.resolve(b)
            if isinstance(a, Var) and isinstance(b, Var) and a is b:
                continue
            if isinstance(a, Var) or isinstance(b, Var):
                if not isinstance(a, Var):
                    a, b = b, a
                if isinstance(b, Var):
                    if a.sort != b.sort:
                        return None
                    ex = st.excl.get(a, set()) | st.excl.get(b, set())
                    if ex:
                        st.excl[b] = ex
                    if a in st.subs:
                        st.subs.setdefault(b, []).extend(st.subs[a])
                    st.sub[a] = b
                else:
                    if a.sort == 'N':
                        return None
                    if b[0] in st.excl.get(a, set()):
                        return None
                    if st.occurs(a, b):
                        return None
                    st.sub[a] = b
            else:
                if a[0] != b[0] or len(a) != len(b):
                    return None
                stack.extend(zip(a[1:], b[1:]))
        if not st.consistent():
            return None
        return st

    def eq_split(self, s, t):
        """Yields (state, bool): decides s == t with case splits."""
        s = self.resolve(s)
        t = self.resolve(t)
        if s == t:
            yield (self, True)
            return
        u = self.unify(s, t)
        if u is None:
            yield (self, False)
            return
        yield (u, True)
        st = self.copy()
        st.diseq.append((s, t))
        yield (st, False)


def subterm_of(t, s, st):
    t = st.resolve(t)
    s = st.resolve(s)
    if t == s:
        return True
    if isinstance(t, Var):
        return False
    return any(subterm_of(a, s, st) for a in t[1:])


class Model:
    def __init__(self, tags, rules, default='J'):
        self.tags = dict(tags)
        self.tags.setdefault('G', 1)
        self.tags.setdefault(default, 2)
        self.rules = list(rules)
        self.default = default
        self.rev = False
        self.vfirst = False

    def match(self, pat, t, st, b, defer=None):
        """Yields (state, bindings-or-None).  Structural (tag) tests are done first; equality
        checks for repeated pattern variables are deferred (collected in `defer`) and decided by
        `finish_deferred` — same semantics, far fewer case splits."""
        if isinstance(pat, str):
            b2 = dict(b)
            if pat in b:
                b2['__d'] = b.get('__d', ()) + ((b[pat], t),)
            else:
                b2[pat] = t
            yield (st, b2)
            return
        tag = pat[0]
        if tag == 'AS':
            name, sub = pat[1], pat[2]
            b2 = dict(b)
            if name in b:
                b2['__d'] = b.get('__d', ()) + ((b[name], t),)
            else:
                b2[name] = t
            yield from self.match(sub, t, st, b2, defer)
            return
        if tag == 'OP':
            b2 = dict(b)
            b2['__d'] = b.get('__d', ()) + (('OP', pat[1], pat[2], t),)
            yield (st, b2)
            return
        t = st.resolve(t)
        if isinstance(t, Var):
            if t.sort == 'N':
                raise ValueError('constructor pattern on Nat atom')
            if tag in st.excl.get(t, set()):
                yield (st, None)
                return
            fresh = [Var('N' if tag == 'G' else 'M') for _ in range(self.tags[tag])]
            st_yes = st.copy()
            st_yes.sub[t] = (tag, *fresh)
            if st_yes.consistent():
                yield from self.match(pat, (tag, *fresh), st_yes, b)
            st_no = st.copy()
            st_no.excl.setdefault(t, set()).add(tag)
            if len(st_no.excl[t]) == len(self.tags):
                return
            yield (st_no, None)
            return
        if t[0] != tag:
            yield (st, None)
            return

        def go(i, st, b):
            if i > len(pat) - 1:
                yield (st, b)
                return
            for st2, b2 in self.match(pat[i], t[i], st, b, defer):
                if b2 is None:
                    yield (st2, None)
                else:
                    yield from go(i + 1, st2, b2)
        yield from go(1, st, b)

    def finish_deferred(self, defer, st, b=None, depth=0):
        """Decide the deferred checks (equalities and OP self-consistency checks); yields (state, ok)."""
        def go(i, st):
            if i == len(defer):
                yield (st, True)
                return
            d = defer[i]
            if len(d) == 4 and d[0] == 'OP':
                _, p1, p2, t = d
                for s2, val in self.eval_pat(('OP', p1, p2), b, st, depth):
                    for st2, ok in s2.eq_split(val, t):
                        if not ok:
                            yield (st2, False)
                        else:
                            yield from go(i + 1, st2)
                return
            a, c = d
            for st2, ok in st.eq_split(a, c):
                if not ok:
                    yield (st2, False)
                else:
                    yield from go(i + 1, st2)
        yield from go(0, st)

    def eval_pat(self, p, b, st, depth=0):
        """Evaluate an instantiated pattern with OP nodes symbolically; yields (state, value)."""
        if isinstance(p, str):
            yield (st, b[p])
            return
        if p[0] == 'OPB':          # ('OPB', name, p1, p2): bind name to op(p1,p2), value = it
            name = p[1]
            for s1, val in self.eval_pat(('OP', p[2], p[3]), b, st, depth):
                b[name] = val
                yield (s1, val)
            return
        if p[0] == 'A1':           # first component of an evaluated value (splits a Var)
            for s1, val in self.eval_pat(p[1], b, st, depth):
                t = s1.resolve(val)
                if isinstance(t, Var):
                    fresh = [Var('M'), Var('M')]
                    st_yes = s1.copy(); st_yes.sub[t] = (self.default, *fresh)
                    if st_yes.consistent() and self.default not in s1.excl.get(t, set()):
                        yield (st_yes, fresh[0])
                    continue   # other constructors: A1 undefined -> no match branch (drop)
                if t[0] == self.default:
                    yield (s1, t[1])
            return
        if p[0] == 'OP':
            for s1, va in self.eval_pat(p[1], b, st, depth):
                for s2, vb in self.eval_pat(p[2], b, s1, depth):
                    if depth >= getattr(self, 'max_op_depth', 2):
                        # unknown result: either the free product, or a proper subterm of an argument
                        yield (s2, (self.default, va, vb))
                        for side in (va, vb):
                            r = Var('M')
                            s3 = s2.copy()
                            s3.subs[r] = [side]
                            yield (s3, r)
                        continue
                    yield from self.op(va, vb, s2, depth + 1)
            return
        def go(i, st, acc):
            if i == len(p):
                yield (st, (p[0],) + tuple(acc))
                return
            for s2, v in self.eval_pat(p[i], b, st, depth):
                yield from go(i + 1, s2, acc + [v])
        yield from go(1, st, [])

    def match_rule(self, pu, pv, u, v, st, depth=0):
        """Yields (state, bindings-or-None) for the whole rule (structural tests first, then the
        deferred equality checks collected in bindings['__d'])."""
        first, second = ((pv, v), (pu, u)) if getattr(self, 'vfirst', False) else ((pu, u), (pv, v))
        for s2, b in self.match(first[0], first[1], st, {}):
            if b is None:
                yield (s2, None)
                continue
            for s3, b2 in self.match(second[0], second[1], s2, b):
                if b2 is None:
                    yield (s3, None)
                    continue
                for s4, ok in self.finish_deferred(b2.get('__d', ()), s3, b2, depth):
                    yield (s4, b2 if ok else None)

    def inst(self, rhs, b):
        if isinstance(rhs, str):
            return b[rhs]
        return (rhs[0],) + tuple(self.inst(a, b) for a in rhs[1:])

    def op(self, u, v, st, depth=0):
        pending = [st]
        for (pu, pv, rhs) in self.rules:
            nxt = []
            for s in pending:
                for s2, b in self.match_rule(pu, pv, u, v, s, depth):
                    if b is None:
                        nxt.append(s2)
                    else:
                        yield (s2, self.inst(rhs, b))
            pending = nxt
        for s in pending:
            yield (s, (self.default, u, v))

    def eval(self, term, env, st):
        if isinstance(term, str):
            yield (st, env[term])
            return
        if getattr(self, 'rev', False):
            for s1, v in self.eval(term[1], env, st):
                for s2, u in self.eval(term[0], env, s1):
                    yield from self.op(u, v, s2)
            return
        for s1, u in self.eval(term[0], env, st):
            for s2, v in self.eval(term[1], env, s1):
                yield from self.op(u, v, s2)

    def verify(self, law, max_fail=None):
        lhs, rhs = law
        vs = sorted(set(_vars(rhs)) | {lhs})
        env = {v: Var('M', v) for v in vs}
        fails = []
        n = 0
        for st, val in self.eval(rhs, env, State()):
            n += 1
            if st.resolve(val) != st.resolve(env[lhs]):
                fails.append((st, env, val))
                if max_fail and len(fails) >= max_fail:
                    break
        return fails, n


def _vars(t):
    if isinstance(t, str):
        return [t]
    return _vars(t[0]) + _vars(t[1])


def pretty(t, st=None):
    if st is not None:
        t = st.resolve(t)
    if isinstance(t, Var):
        return repr(t)
    if t[0] == 'G':
        return 'g' + pretty(t[1], st)
    return t[0] + '(' + ','.join(pretty(a, st) for a in t[1:]) + ')'


def describe_fail(f):
    st, env, val = f
    parts = [f"{k}={pretty(v, st)}" for k, v in env.items()]
    ds = [f"{pretty(a, st)}!={pretty(b, st)}" for a, b in st.diseq]
    ex = [f"{v!r} not in {sorted(s)}" for v, s in st.excl.items() if isinstance(st.resolve(v), Var)]
    return ' '.join(parts) + ' -> ' + pretty(val, st) + ('  | ' + ', '.join(ds) if ds else '') + ('  | ' + ', '.join(ex) if ex else '')


