"""Does the law force the TRIVIAL magma?   (i.e. does eq1 |- x = y ?)

The free algebra of the variety defined by `x = RHS(x,y,..)` is the term algebra modulo the
congruence generated by all instances of the law.  Build that congruence with an e-graph over a
bounded term pool and ask whether two DISTINCT GENERATORS end up in the same class.

  merged   => the law forces the trivial magma => eq1 => eq2 for EVERY eq2 => the rows are TRUE.
  not merged at this bound => NOT evidence either way (the pool is bounded); report the bound.

Every union is justified by one instance of the law, so a merge is a PROOF; the absence of one is
only a bound.  Saturation: after each round the class representatives are fed back into the pool.

usage: python gen/_p2_trivial.py <eq> [poolsize=5] [gens=2] [maxsz=60] [rounds=3]
"""
import sys, os, itertools, collections, time
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE)); sys.path.insert(0, HERE)
from freemodel import normalise, catalog, pvars
from laws import parse_eq


def dual_pat(p):
    return p if isinstance(p, str) else (dual_pat(p[1]), dual_pat(p[0]))


def show(t):
    return 'g%d' % t[1] if t[0] == 'g' else '(%s*%s)' % (show(t[1]), show(t[2]))


SZ = {}


def sz(t):
    r = SZ.get(t)
    if r is None:
        r = 1 if t[0] == 'g' else 1 + sz(t[1]) + sz(t[2])
        SZ[t] = r
    return r


def terms_upto(maxsize, gens):
    by = {1: [('g', i) for i in range(gens)]}
    for n in range(3, maxsize + 1, 2):
        by[n] = []
        for a in range(1, n - 1, 2):
            b = n - 1 - a
            if b in by:
                for s in by[a]:
                    for t in by[b]:
                        by[n].append(('J', s, t))
    out = []
    for n in sorted(by):
        out += by[n]
    return out


class EG:
    def __init__(self, maxsz):
        self.par = {}
        self.maxsz = maxsz
        self.kids = {}
        self.why = {}

    def add(self, t):
        if t in self.par:
            return t
        if sz(t) > self.maxsz:
            return None
        if t[0] == 'J':
            if self.add(t[1]) is None or self.add(t[2]) is None:
                return None
            self.par[t] = t
            self.kids[t] = (t[1], t[2])
        else:
            self.par[t] = t
        return t

    def find(self, t):
        r = t
        while self.par[r] != r:
            r = self.par[r]
        while self.par[t] != r:
            self.par[t], t = r, self.par[t]
        return r

    def union(self, a, b, why):
        ra, rb = self.find(a), self.find(b)
        if ra == rb:
            return False
        if sz(rb) < sz(ra):
            ra, rb = rb, ra
        self.par[rb] = ra
        self.why.setdefault((rb, ra), why)
        return True

    def congruence(self, rounds=60):
        for _ in range(rounds):
            sigs = {}
            changed = False
            for t, (a, b) in self.kids.items():
                k = (self.find(a), self.find(b))
                if k in sigs:
                    changed |= self.union(sigs[k], t, 'congruence')
                else:
                    sigs[k] = t
            if not changed:
                return True
        return False


def run(eq, poolsize, gens, maxsz, rounds):
    cat = catalog()
    orig = normalise(parse_eq(cat[eq]))
    dualized = isinstance(orig[1][1], str) and not isinstance(orig[1][0], str)
    law = ('x', dual_pat(orig[1])) if dualized else orig
    vs = pvars(law[1])
    G = EG(maxsz)
    pool = terms_upto(poolsize, gens)
    for t in pool:
        G.add(t)
    gs = [('g', i) for i in range(gens)]
    print('law %d  vars=%s  gens=%d  pool=%d  maxsz=%d' % (eq, vs, gens, len(pool), maxsz))

    def build(p, s):
        if isinstance(p, str):
            return s[p]
        return ('J', build(p[0], s), build(p[1], s))

    for rd in range(rounds):
        t0 = time.time()
        n = skipped = 0
        pend = []
        for vals in itertools.product(pool, repeat=len(vs)):
            s = dict(zip(vs, vals))
            rhs = build(law[1], s)
            if G.add(rhs) is None:
                skipped += 1
                continue
            n += 1
            pend.append((s['x'], rhs, s))
        for a, b, s in pend:
            G.union(a, b, s)
        ok = G.congruence()
        cls = collections.defaultdict(list)
        for t in list(G.par):
            cls[G.find(t)].append(t)
        merged = len(set(G.find(g) for g in gs)) < gens
        print('  round %d: %d instances (%d over size), %d terms, %d classes, congruence %s (%.1fs)'
              % (rd, n, skipped, len(G.par), len(cls), 'closed' if ok else 'NOT CLOSED',
                 time.time() - t0))
        if merged:
            print('  *** GENERATORS MERGED -- the law forces the TRIVIAL magma ***')
            for i in range(gens):
                for j in range(i + 1, gens):
                    if G.find(gs[i]) == G.find(gs[j]):
                        print('      g%d ~ g%d' % (i, j))
            return True
        # feed back: the smallest representative of each class, plus the smallest few new terms
        reps = sorted({G.find(t) for t in G.par}, key=sz)
        newpool = [t for t in reps if sz(t) <= poolsize + 2][:len(pool) + 6]
        if set(newpool) == set(pool):
            print('  pool stable -- saturated at this bound')
            break
        pool = newpool
    print('  NO generator merge at this bound (pool<=%d, maxsz=%d) -- NOT evidence of non-triviality'
          % (poolsize, maxsz))
    big = sorted(((len(v), k) for k, v in cls.items()), reverse=True)[:3]
    print('  largest classes: %s ; smallest merged pair in a class:' % [k for k, _ in big])
    for k, r in big[:2]:
        ms = sorted(cls[r], key=sz)[:2]
        if len(ms) == 2:
            print('    %s  ~  %s' % (show(ms[0])[:50], show(ms[1])[:50]))
    return False


if __name__ == '__main__':
    eq = int(sys.argv[1])
    ps = int(sys.argv[2]) if len(sys.argv) > 2 else 5
    gn = int(sys.argv[3]) if len(sys.argv) > 3 else 2
    mz = int(sys.argv[4]) if len(sys.argv) > 4 else 60
    rd = int(sys.argv[5]) if len(sys.argv) > 5 else 3
    run(eq, ps, gn, mz, rd)
