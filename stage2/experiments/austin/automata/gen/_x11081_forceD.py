"""Force the decode rule at the D product (op B C) and at B, for lab2 models.
D = op(B,C) with B = op(x, op(y,x)) and C = op(z,y).  The attacker controls z entirely, so set
    z := E q (op B q)      -- then a1 C = z, a2 (a1 C) = op B (a1 (a1 C)), i.e. D's core holds.
This is the construction that killed x12/y12/w123; it is NOT generated by any encoding-planting pool.
usage: python gen/_x11081_forceD.py <ver>"""
import sys, collections
sys.path.insert(0, 'c:/Users/nacho/Documents/GitHub/magma-ai/stage2/experiments/austin/automata/gen')
from _x11081_lab2 import Model, chain, prof, terms, sz, show, g, J, E, F, tg, a1, a2

VER = sys.argv[1] if len(sys.argv) > 1 else 'v11'
T3 = terms(3, 2)
T5 = terms(5, 2)
tot = 0
fails = []
profs = collections.Counter()


def test(x, y, z, tag):
    global tot
    M = Model(VER)
    try:
        A, B, C, D, R = chain(M, x, y, z)
        p = prof(M, x, y, z)
    except RecursionError:
        return
    tot += 1
    profs[p] += 1
    if R != x:
        fails.append((tag, x, y, z, R, p))


POOL = T3 + T5[:60]
for x in POOL[:40]:
    for y in POOL[:40]:
        M = Model(VER)
        try:
            A = M.op(y, x)
            B = M.op(x, A)
        except RecursionError:
            continue
        for q in T3[:4]:
            try:
                r = M.op(B, q)
            except RecursionError:
                continue
            for ctor in (E, F, J):
                z = ctor(q, r)
                if sz(z) > 400:
                    continue
                test(x, y, z, 'Dforce-' + ctor(g(0), g(0))[0])
        # also force B: make a1 A tagged so op(x,A) can decode
        for w in T3[:3]:
            test(x, E(w, x), g(0), 'Bforce')
            test(x, F(w, x), g(1), 'Bforce2')
print('%s: %d chains, %d FAILS' % (VER, tot, len(fails)))
print('profiles:', dict(profs.most_common(8)))
fails.sort(key=lambda f: sz(f[1]) + sz(f[2]) + sz(f[3]))
for (tag, x, y, z, R, p) in fails[:2]:
    print('FAIL %s profile %s' % (tag, str(p)))
    for nm, t in (('x', x), ('y', y), ('z', z), ('R', R)):
        print('  %s (sz %d) = %s' % (nm, sz(t), show(t)[:200]))
