"""Anchored-carrier oracle: restrict the carrier to the IMAGE of the free magma under evaluation.

The carrier of every model in this family is a term algebra; the law quantifies over all of it, which is
what hands the adversary its forged terms.  Here the carrier is the subalgebra generated by the
generators = { ev(w) : w in free magma }.  Satisfaction of an equation passes DOWN to subalgebras, so
this can only remove failures.

Usage as a library:  build(Model_instance_factory, ngens, wdepth)  ->  (list of image terms, ev map)
"""
import itertools, random, sys

def image(M, ngens=2, wsize=5, cap=4000, gmk=None):
    """All ev(w) for w a free-magma term with <= wsize leaves.  Returns (terms_sorted, by_wsize)."""
    gterms = [gmk(i) for i in range(ngens)]
    by = {1: list(gterms)}
    seen = set(gterms)
    for s in range(2, wsize + 1):
        out = []
        for i in range(1, s):
            for a in by.get(i, []):
                for b in by.get(s - i, []):
                    try:
                        r = M.op(a, b)
                    except RecursionError:
                        continue
                    out.append(r)
        # dedupe within level, keep everything (a value may recur at several levels)
        nd = []
        for r in out:
            if r not in seen:
                seen.add(r); nd.append(r)
        by[s] = nd
        if len(seen) > cap:
            break
    return by, seen


def law_sweep(M, law_fn, pool, limit=None, rng=None, sample=None):
    """Run law_fn(M,x,y,z) -> (ok, info) over triples from pool."""
    fails, tot = [], 0
    if sample:
        rng = rng or random.Random(0)
        it = ((rng.choice(pool), rng.choice(pool), rng.choice(pool)) for _ in range(sample))
    else:
        it = itertools.product(pool, pool, pool)
    for (x, y, z) in it:
        if limit and tot >= limit:
            break
        try:
            ok, info = law_fn(M, x, y, z)
        except RecursionError:
            continue
        tot += 1
        if not ok:
            fails.append((x, y, z, info))
    return tot, fails
